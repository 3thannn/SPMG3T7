import { test, expect } from './ariel-fixtures'

test.describe.configure({ timeout: 180_000 })

test('SPMG3T7-65: Coordinator requests, edits and removes; Tech Support sees notes', async ({ page, world }) => {
  const event = await world.event()
  const item = await world.item()
  await world.open(page, 'coordinator', `/events/${event.id}`)
  const section = page.getByRole('region', { name: 'Equipment requests', exact: true })
  await section.getByLabel('Catalogue item', { exact: true }).selectOption(item.id)
  await expect(section.getByLabel('Needed from', { exact: true })).toHaveValue(event.startsAt.slice(0, 16))
  await section.getByLabel('Quantity', { exact: true }).fill('2')
  await section.getByLabel('Technical requirements (optional)', { exact: true }).fill('HDMI input')
  await section.getByRole('button', { name: 'Request equipment', exact: true }).click()
  const row = section.getByRole('listitem').filter({ hasText: item.name })
  await expect(row).toContainText('Requested')
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await row.getByLabel('Quantity', { exact: true }).fill('3')
  await row.getByRole('button', { name: 'Save request', exact: true }).click()
  await expect(row).toContainText('Quantity: 3')
  const lines = await world.call<{ id: string }[]>('coordinator', 'GET', `/events/${event.id}/equipment-requests`)
  await world.open(page, 'tech', '/equipment-requests')
  await expect(page.getByRole('list', { name: 'Equipment request queue' })).toContainText(event.title)
  await page.goto(`/#/equipment-requests/${lines[0].id}`)
  await page.getByRole('button', { name: 'Update request', exact: true }).click()
  await page.getByLabel('Arrangement notes', { exact: true }).fill('Bring HDMI adapter')
  await page.getByRole('button', { name: 'Save request', exact: true }).click()
  await expect(page.getByText('Request updated.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Bring HDMI adapter', { exact: true })).toBeVisible()
  await world.open(page, 'coordinator', `/events/${event.id}`)
  await expect(row).toContainText('Bring HDMI adapter')
  await row.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(row.locator('.equipment-request-status')).toHaveText('Removed')
  await expect(row.getByRole('button', { name: 'Remove', exact: true })).toHaveCount(0)
  await expect(row.getByRole('button', { name: 'Edit', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(row.locator('.equipment-request-status')).toHaveText('Removed')
})

test('SPMG3T7-77: overlapping reservations subtract stock and show shortfall', async ({ page, world }) => {
  const a = await world.event('Planning', 'reservation A')
  const b = await world.event('Planning', 'reservation B')
  const item = await world.item()
  const first = await world.call<{ id: string; version: number }>('coordinator', 'POST', `/events/${a.id}/equipment-requests`, { equipmentId: Number(item.id), quantity: 6 })
  const second = await world.call<{ id: string; version: number }>('coordinator', 'POST', `/events/${b.id}/equipment-requests`, { equipmentId: Number(item.id), quantity: 3 })
  await world.open(page, 'tech', `/equipment-requests/${first.id}`)
  await page.getByRole('button', { name: 'Reserve', exact: true }).click()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Reserved')
  await page.reload()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Reserved')
  await page.goto(`/#/equipment-requests/${second.id}`)
  await expect(page.getByRole('status').filter({ hasText: 'Shortfall: 1' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reserve', exact: true })).toBeDisabled()
  const stock = await world.call<{ availableQuantity: number; reservedQuantity: number }[]>('tech', 'GET', `/equipment-requests/${second.id}/availability`)
  expect(stock[0]).toMatchObject({ availableQuantity: 2, reservedQuantity: 6 })
  expect((await world.response('tech', 'POST', `/equipment-requests/${second.id}/reserve`, { version: second.version, equipmentId: Number(item.id) })).status()).toBe(409)
  await page.getByRole('button', { name: 'Mark Unavailable', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Give a reason')
  await page.getByLabel('Reason for Unavailable', { exact: true }).fill('Only two units remain')
  await page.getByRole('button', { name: 'Mark Unavailable', exact: true }).click()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Unavailable')
  await world.open(page, 'coordinator', `/events/${b.id}`)
  await expect(page.getByRole('region', { name: 'Equipment requests', exact: true })).toContainText('Only two units remain')
  await page.goto('/#/notifications')
  await expect(page.locator('.notification-list').first()).toContainText(b.title)
})
