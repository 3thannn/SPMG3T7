import { test, expect } from './ariel-fixtures'

test('SPMG3T7-77: overlapping reservations subtract stock and show shortfall', async ({ page, world }) => {
  const a = await world.event('Planning', 'reservation A')
  const b = await world.event('Planning', 'reservation B')
  const item = await world.item()
  const first = await world.call<{ id: string; version: number }>('coordinator', 'POST', `/events/${a.id}/equipment-requests`, { equipmentId: Number(item.id), quantity: 6 })
  const second = await world.call<{ id: string; version: number }>('coordinator', 'POST', `/events/${b.id}/equipment-requests`, { equipmentId: Number(item.id), quantity: 3 })
  await world.open(page, 'tech', `/equipment-requests/${first.id}`)
  await page.getByRole('button', { name: 'Reserve', exact: true }).click()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Reserved')
  await page.reload()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Reserved')
  await page.goto(`/#/equipment-requests/${second.id}`)
  await expect(page.getByRole('status').filter({ hasText: 'Shortfall: 1' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reserve', exact: true })).toBeDisabled()
  const stock = await world.call<{ availableQuantity: number; reservedQuantity: number }[]>('tech', 'GET', `/equipment-requests/${second.id}/availability`)
  expect(stock[0]).toMatchObject({ availableQuantity: 2, reservedQuantity: 6 })
  expect((await world.response('tech', 'POST', `/equipment-requests/${second.id}/reserve`, { version: second.version, equipmentId: Number(item.id) })).status()).toBe(409)
  await page.getByRole('button', { name: 'Mark Unavailable', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Give a reason')
  await page.getByLabel('Reason for Unavailable', { exact: true }).fill('Only two units remain')
  await page.getByRole('button', { name: 'Mark Unavailable', exact: true }).click()
  await expect(page.locator('.equipment-request-detail-head')).toContainText('Unavailable')
  await world.open(page, 'coordinator', `/events/${b.id}`)
  await expect(page.getByRole('region', { name: 'Equipment requests', exact: true })).toContainText('Only two units remain')
  await page.goto('/#/notifications')
  await expect(page.locator('.notification-list').first()).toContainText(b.title)
})
